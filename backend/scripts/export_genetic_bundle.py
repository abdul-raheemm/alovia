"""Writes both apps' genetic form and result texts (packages/shared), generated from
backend/rules/genetic/*.yaml so the form offers exactly what the engine accepts (Genetic spec §5)
and the result screen uses the rule files' words and messages.

  python scripts/export_genetic_bundle.py

tests/unit/test_genetic_bundle.py fails if the committed file is out of date.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.modules.genetic.rules import GeneticRules, parse_genetic_rules  # noqa: E402

OUT = (
    Path(__file__).resolve().parents[2]
    / "frontend"
    / "packages"
    / "shared"
    / "src"
    / "geneticBundle.generated.ts"
)


def render(rules: GeneticRules) -> str:
    labels = rules.labels
    bundle = {
        "rulesVersion": rules.settings.rules_version,
        "conditions": labels.conditions,
        "questionNames": labels.question_names,
        "entryQuestion": labels.entry_question,
        "entryAnswers": labels.entry_answers,
        "previousChildQuestion": labels.previous_child_question,
        "previousChildAnswers": labels.previous_child_answers,
        "consanguinityQuestion": labels.consanguinity_question,
        "consanguinityAnswers": labels.consanguinity_answers,
        # form statuses per condition and parent (§5.1-5.3); API-only values are not offered
        "statuses": {
            "haemoglobin_group": {
                "mother": {s: label for s, (_, label) in rules.haemoglobin.statuses.items()},
                "father": {s: label for s, (_, label) in rules.haemoglobin.statuses.items()},
            },
            "haemophilia": {
                "mother": rules.haemophilia.statuses.mother,
                "father": rules.haemophilia.statuses.father,
            },
            "marfan": {"mother": rules.marfan.statuses, "father": rules.marfan.statuses},
        },
        "evidence": {
            name: {
                "label": kind.label,
                "conditions": list(kind.conditions),
                "haemoglobinStatuses": list(kind.haemoglobin_statuses)
                if kind.haemoglobin_statuses
                else None,
            }
            for name, kind in rules.evidence.evidence.items()
        },
        "outcomes": labels.outcomes,
        "chances": labels.chances,
        "messages": {key: m.text for key, m in rules.messages.items()},
    }
    body = json.dumps(bundle, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by backend/scripts/export_genetic_bundle.py from backend/rules/genetic.\n"
        "// Do not edit by hand: change the rule files and run the script again.\n"
        f"export const GENETIC_BUNDLE = {body} as const\n"
    )


def main() -> None:
    OUT.write_text(render(parse_genetic_rules()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
