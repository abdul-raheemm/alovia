"""Writes the patient app's bundled symptom texts (DEC-060, DEC-061, ERROR_HANDLING.md):
the warning signs, the advice messages and the official phone numbers, generated from
backend/rules/symptoms/*.yaml so the urgent page still works when the backend is down.

  python scripts/export_symptom_bundle.py

tests/unit/test_symptom_bundle.py fails if the committed file is out of date.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.modules.symptoms.rules import SymptomRules, parse_symptom_rules  # noqa: E402

OUT = (
    Path(__file__).resolve().parents[2]
    / "frontend"
    / "apps"
    / "patient-web"
    / "src"
    / "app"
    / "symptomBundle.generated.ts"
)


def render(rules: SymptomRules) -> str:
    bundle = {
        "rulesVersion": rules.settings.rules_version,
        "warning": [
            {
                "id": s.id,
                "label": s.label,
                "fromWeek": getattr(rules.settings, s.from_week_setting)
                if s.from_week_setting
                else None,
                "labourDuration": s.labour_duration,
            }
            for s in rules.vocabulary.warning
        ],
        "labourDurations": rules.vocabulary.labour_durations,
        "messages": {key: m.text for key, m in rules.messages.items()},
        "helplines": {
            h.key: {
                "label": h.label,
                "numbers": list(h.numbers),
                "sourceTitle": h.source_title,
                "sourceUrl": h.source_url,
            }
            for h in rules.helplines
        },
    }
    body = json.dumps(bundle, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by backend/scripts/export_symptom_bundle.py from backend/rules/symptoms.\n"
        "// Do not edit by hand: change the rule files and run the script again.\n"
        f"export const SYMPTOM_BUNDLE = {body} as const\n"
    )


def main() -> None:
    OUT.write_text(render(parse_symptom_rules()), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
